
-- =========================================================
-- V6: CREATE COUNTRY CURRENCY MASTER
-- =========================================================

CREATE TABLE IF NOT EXISTS ecommerce.country_currency_master (
    country_currency_master_id INT4 GENERATED BY DEFAULT AS IDENTITY
        (INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647
         START 1 CACHE 1 NO CYCLE) NOT NULL,

    country_id INT4 NULL,
    created_by INT4 NULL,
    created_date TIMESTAMP(6) NULL,
    currency_code VARCHAR(255) NULL,
    currency_name VARCHAR(255) NULL,
    currency_symbol VARCHAR(255) NULL,
    deleted VARCHAR(255) NULL,
    ip_address VARCHAR(255) NULL,
    mac_id VARCHAR(255) NULL,
    status VARCHAR(255) NULL,
    updated_by INT4 NULL,
    updated_date TIMESTAMP(6) NULL,

    CONSTRAINT country_currency_master_pkey
        PRIMARY KEY (country_currency_master_id)
);

-- =========================================================
-- SEED COUNTRY CURRENCIES
-- =========================================================

