CREATE SCHEMA IF NOT EXISTS ecommerce;

CREATE TABLE IF NOT EXISTS ecommerce.menu_type_master (
    menu_type_id INT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    created_by INT,
    created_date TIMESTAMP(6),
    deleted VARCHAR(255),
    ip_address VARCHAR(255),
    mac_id VARCHAR(255),
    menu_type_name VARCHAR(255),
    status VARCHAR(255),
    updated_by INT,
    updated_date TIMESTAMP(6)
);