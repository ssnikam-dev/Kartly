
CREATE TABLE IF NOT EXISTS ecommerce.country_master (
    country_id INT4 GENERATED BY DEFAULT AS IDENTITY
        (INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647
         START 1 CACHE 1 NO CYCLE) NOT NULL,
    country_flag VARCHAR(255),
    country_location_levels INT4,
    country_name VARCHAR(255),
    created_by INT4,
    created_date TIMESTAMP(6),
    deleted VARCHAR(255),
    ip_address VARCHAR(255),
    mac_id VARCHAR(255),
    status VARCHAR(255),
    updated_by INT4,
    updated_date TIMESTAMP(6),
    CONSTRAINT country_master_pkey PRIMARY KEY (country_id)
);

