CREATE TABLE IF NOT EXISTS ecommerce.sub_module_master (
    sub_module_id INT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    created_by INT,
    created_date TIMESTAMP(6),
    deleted VARCHAR(255),
    device_from VARCHAR(255),
    icon VARCHAR(255),
    ip_address VARCHAR(255),
    mac_id VARCHAR(255),
    menu_type_id INT,
    parent_id INT,
    request_mapping VARCHAR(255),
    status VARCHAR(255),
    sub_module_name VARCHAR(255),
    updated_by INT,
    updated_date TIMESTAMP(6)
);